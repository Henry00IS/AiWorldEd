import type { Vector3 } from 'three';
import type { SolidPlane } from '@/solid/brush/solid_plane.js';
import type { ModifierBevelFaceRecord } from './modifier_bevel_face_record.js';
import type { ModifierBevelDerivedBrush } from './modifier_bevel_derived.js';
import type { ModifierBevelGirder } from './modifier_bevel_uv_girder.js';
import { modifierBevelCenterPlane } from './modifier_bevel_center_plane.js';
import {
  modifierBevelCutLoop,
  modifierBevelLoopArea,
  type ModifierBevelBisectPlan,
} from './modifier_bevel_corner_face_bisect.js';
import { modifierBevelApplyBisectPlans } from './modifier_bevel_corner_face_bisect_apply.js';
import { modifierBevelFaceLoops } from './modifier_bevel_corner_face_rebuild.js';
import { modifierBevelNeighborFaces, modifierBevelSharedEdge } from './modifier_bevel_face_graph.js';
import { modifierBevelGirderForFace } from './modifier_bevel_profile_cylinder.js';
import { modifierBevelProfileStrip } from './modifier_bevel_uv_layout_profile.js';

/** One piece of a strip and the wall it keeps. */
interface ModifierBevelLipPiece {
  /** Piece vertices. */
  loop: Vector3[];
  /** Authored parent. */
  parent: number;
}

/**
 * Cuts the end of a profile strip where it crosses into the next edge.
 *
 * @param shell Derived brush.
 * @param records Face records.
 */
export function modifierBevelApplyStripLips(
  shell: ModifierBevelDerivedBrush,
  records: ModifierBevelFaceRecord[],
): void {
  const count = records.length;
  for (let face = 0; face < count; face += 1) modifierBevelApplyOneStripLip(shell, records, face);
  modifierBevelAnchorLipSmears(records);
}

/**
 * Gives a cut band the wall it meets beyond the center plane.
 *
 * @param shell Derived brush.
 * @param records Face records.
 */
export function modifierBevelClaimCutBands(shell: ModifierBevelDerivedBrush, records: ModifierBevelFaceRecord[]): void {
  const seen = new Set<number>();
  for (let face = 0; face < records.length; face += 1) modifierBevelClaimOneBand(shell, records, seen, face);
  modifierBevelAnchorLipSmears(records);
}

/**
 * Claims one band when its far side is a single wall.
 *
 * @param shell Derived brush.
 * @param records Face records.
 * @param seen Faces already considered.
 * @param face Candidate face.
 */
function modifierBevelClaimOneBand(
  shell: ModifierBevelDerivedBrush,
  records: ModifierBevelFaceRecord[],
  seen: Set<number>,
  face: number,
): void {
  if (seen.has(face) || !modifierBevelBandStart(shell, records, face)) return;
  const plane = modifierBevelBandPlane(shell, face);
  const band = modifierBevelCutBand(shell, records, face, plane);
  const parent = modifierBevelBandParent(shell, records, band);
  if (!plane || parent < 0 || !modifierBevelBandStaysCut(shell, records, band)) return;
  for (const index of band) seen.add(index);
  modifierBevelPaintBand(records, band, parent);
}

/**
 * Returns whether a face sits on a center cut and also meets another wall.
 *
 * @param shell Derived brush.
 * @param records Face records.
 * @param face Face index.
 * @returns True when the face can start a band.
 */
function modifierBevelBandStart(
  shell: ModifierBevelDerivedBrush,
  records: readonly ModifierBevelFaceRecord[],
  face: number,
): boolean {
  if (!modifierBevelGeneratedFace(records, face)) return false;
  return modifierBevelHasPlaneEdge(shell, face) && modifierBevelHasForeignEdge(shell, records, face);
}

/**
 * Returns whether a record was generated by the bevel.
 *
 * @param records Face records.
 * @param face Face index.
 * @returns True for a strip or a cap.
 */
function modifierBevelGeneratedFace(records: readonly ModifierBevelFaceRecord[], face: number): boolean {
  const record = records[face];
  return !!record && (record.cornerFace || record.chamferEdge !== null);
}

/**
 * Cuts one strip where a neighboring center plane leaves a lip.
 *
 * @param shell Derived brush.
 * @param records Face records.
 * @param face Strip face.
 */
function modifierBevelApplyOneStripLip(
  shell: ModifierBevelDerivedBrush,
  records: ModifierBevelFaceRecord[],
  face: number,
): void {
  if (!modifierBevelStripNeedsLip(shell, face)) return;
  const loops = modifierBevelFaceLoops(shell.localBrush);
  const plan = modifierBevelStripLipPlan(shell, records, loops, face);
  if (!plan) return;
  modifierBevelApplyBisectPlans(shell, records, loops, [plan]);
}

/**
 * Builds the cut of one strip by every neighboring edge it crosses.
 *
 * @param shell Derived brush.
 * @param records Face records.
 * @param loops Face loops.
 * @param face Strip face.
 * @returns Cut, or null when the strip stays on its own side.
 */
function modifierBevelStripLipPlan(
  shell: ModifierBevelDerivedBrush,
  records: readonly ModifierBevelFaceRecord[],
  loops: readonly Vector3[][],
  face: number,
): ModifierBevelBisectPlan | null {
  const loop = loops[face];
  const parent = records[face]?.parentSurfaceIndex ?? -1;
  if (!loop || parent < 0 || !modifierBevelProfileStrip(shell, face)) return null;
  const pieces = modifierBevelCutStripLips(shell, face, loop, parent);
  if (pieces.length < 2) return null;
  return modifierBevelLipBisectPlan(face, pieces);
}

/**
 * Splits a loop by each neighboring center plane that leaves a lip.
 *
 * @param shell Derived brush.
 * @param face Strip face.
 * @param loop Strip vertices.
 * @param parent Strip parent.
 * @returns Pieces. One entry when nothing was cut.
 */
function modifierBevelCutStripLips(
  shell: ModifierBevelDerivedBrush,
  face: number,
  loop: readonly Vector3[],
  parent: number,
): ModifierBevelLipPiece[] {
  let pieces = [modifierBevelLipPiece(loop, parent)];
  for (const plane of modifierBevelNeighborLipPlanes(shell, face)) pieces = modifierBevelApplyLipCut(pieces, plane);
  return pieces;
}

/**
 * Stores one loop under a parent.
 *
 * @param loop Face vertices.
 * @param parent Authored parent.
 * @returns Piece.
 */
function modifierBevelLipPiece(loop: readonly Vector3[], parent: number): ModifierBevelLipPiece {
  return { loop: loop.map((point) => point.clone()), parent };
}

/**
 * Lists center planes of edges that meet this strip's edge.
 *
 * @param shell Derived brush.
 * @param face Strip face.
 * @returns Planes.
 */
function modifierBevelNeighborLipPlanes(shell: ModifierBevelDerivedBrush, face: number): SolidPlane[] {
  const planes: SolidPlane[] = [];
  const girder = modifierBevelStripGirder(shell, face);
  if (!girder) return planes;
  for (const other of shell.girders) modifierBevelPushLipPlane(planes, girder, other);
  return planes;
}

/**
 * Returns whether a strip crosses a neighboring center plane by a lip.
 *
 * @param shell Derived brush.
 * @param face Face index.
 * @returns True when a lip cut is worth building.
 */
function modifierBevelStripNeedsLip(shell: ModifierBevelDerivedBrush, face: number): boolean {
  if (!modifierBevelProfileStrip(shell, face)) return false;
  const polygon = shell.localBrush.faces[face];
  const loop = polygon ? shell.localBrush.getFaceVertices(polygon) : [];
  return modifierBevelNeighborLipPlanes(shell, face).some((plane) => modifierBevelLoopIsLip(loop, plane));
}

/**
 * Returns whether one plane leaves a shallow lip on a loop.
 *
 * @param loop Face vertices.
 * @param plane Center plane.
 * @returns True when the loop crosses and one side is shallow.
 */
function modifierBevelLoopIsLip(loop: readonly Vector3[], plane: SolidPlane): boolean {
  const span = modifierBevelLoopSpan(loop, plane);
  if (span.low >= -1.2e-4 || span.high <= 1.2e-4) return false;
  const small = Math.min(Math.abs(span.low), span.high);
  const large = Math.max(Math.abs(span.low), span.high);
  return modifierBevelDepthIsLip(small, large);
}

/**
 * Returns the signed-distance range of a loop.
 *
 * @param loop Face vertices.
 * @param plane Center plane.
 * @returns Lowest and highest distance.
 */
function modifierBevelLoopSpan(loop: readonly Vector3[], plane: SolidPlane): { low: number; high: number } {
  let low = Number.POSITIVE_INFINITY;
  let high = Number.NEGATIVE_INFINITY;
  for (const point of loop) {
    const distance = plane.signedDistance(point);
    low = Math.min(low, distance);
    high = Math.max(high, distance);
  }
  return { low, high };
}

/**
 * Returns whether a shallow side is small enough to be a lip.
 *
 * @param small Distance of the nearer side.
 * @param large Distance of the farther side.
 * @returns True when the nearer side is a lip.
 */
function modifierBevelDepthIsLip(small: number, large: number): boolean {
  return small <= 0.02 && small * 3 < large;
}

/**
 * Returns the girder stored for a strip, or the cylinder that contains it.
 *
 * @param shell Derived brush.
 * @param face Strip face.
 * @returns Girder, or undefined when the strip has none.
 */
function modifierBevelStripGirder(shell: ModifierBevelDerivedBrush, face: number): ModifierBevelGirder | undefined {
  const stored = shell.girderOfFace[face] ?? -1;
  const index = stored >= 0 ? stored : modifierBevelGirderForFace(shell.localBrush, shell.girders, face);
  return shell.girders[index];
}

/**
 * Adds one neighbor plane when the edges share a vertex.
 *
 * @param planes Plane accumulator.
 * @param girder Strip edge.
 * @param other Candidate edge.
 */
function modifierBevelPushLipPlane(
  planes: SolidPlane[],
  girder: ModifierBevelGirder,
  other: ModifierBevelGirder,
): void {
  if (other === girder || !modifierBevelGirdersMeet(girder, other)) return;
  const plane = modifierBevelCenterPlane(other);
  if (plane) planes.push(plane);
}

/**
 * Returns whether two edges share an endpoint.
 *
 * @param left First edge.
 * @param right Second edge.
 * @returns True when an endpoint matches.
 */
function modifierBevelGirdersMeet(left: ModifierBevelGirder, right: ModifierBevelGirder): boolean {
  return modifierBevelEndpointHits(left.start, right) || modifierBevelEndpointHits(left.end, right);
}

/**
 * Returns whether a point is an endpoint of an edge.
 *
 * @param point Candidate.
 * @param girder Edge.
 * @returns True when the point matches either end.
 */
function modifierBevelEndpointHits(point: Vector3, girder: ModifierBevelGirder): boolean {
  return point.distanceToSquared(girder.start) <= 1e-8 || point.distanceToSquared(girder.end) <= 1e-8;
}

/**
 * Cuts every current piece by one plane.
 *
 * @param pieces Pieces so far.
 * @param plane Neighbor plane.
 * @returns Replacement pieces.
 */
function modifierBevelApplyLipCut(
  pieces: readonly ModifierBevelLipPiece[],
  plane: SolidPlane,
): ModifierBevelLipPiece[] {
  const next: ModifierBevelLipPiece[] = [];
  for (const piece of pieces) modifierBevelPushLipPieces(next, piece, plane);
  return next;
}

/**
 * Appends a piece, or both sides when the plane leaves a lip.
 *
 * @param next Accumulator.
 * @param piece Piece to cut.
 * @param plane Neighbor plane.
 */
function modifierBevelPushLipPieces(
  next: ModifierBevelLipPiece[],
  piece: ModifierBevelLipPiece,
  plane: SolidPlane,
): void {
  const parts = modifierBevelCutLoop(piece.loop, [plane]);
  if (!modifierBevelClearLip(parts, plane)) {
    next.push(piece);
    return;
  }
  modifierBevelStoreLipParts(next, parts, piece.parent);
}

/**
 * Returns whether the smaller side is a lip rather than another full sector.
 *
 * @param parts Sides of the cut.
 * @param plane Center plane.
 * @returns True when one side is a shallow lip.
 */
function modifierBevelClearLip(parts: readonly Vector3[][], plane: SolidPlane): boolean {
  if (parts.length < 2) return false;
  const lip = modifierBevelSmallerPart(parts);
  const body = modifierBevelLargerPart(parts);
  const lipArea = modifierBevelLoopArea(parts[lip] ?? []);
  const bodyArea = modifierBevelLoopArea(parts[body] ?? []);
  return modifierBevelPenetration(parts[lip], plane) <= 0.02 && lipArea * 3 < bodyArea;
}

/**
 * Stores each side under the parent the strip already had.
 *
 * @param next Accumulator.
 * @param parts Sides of the cut.
 * @param parent Parent of the uncut piece.
 */
function modifierBevelStoreLipParts(next: ModifierBevelLipPiece[], parts: readonly Vector3[][], parent: number): void {
  for (const loop of parts) {
    if (!loop) continue;
    next.push({ loop, parent });
  }
}

/**
 * Returns the index of the side with less area.
 *
 * @param parts Sides of the cut.
 * @returns Index.
 */
function modifierBevelSmallerPart(parts: readonly Vector3[][]): number {
  return modifierBevelAreaPart(parts, true);
}

/**
 * Returns the index of the side with more area.
 *
 * @param parts Sides of the cut.
 * @returns Index.
 */
function modifierBevelLargerPart(parts: readonly Vector3[][]): number {
  return modifierBevelAreaPart(parts, false);
}

/**
 * Returns the index of the smaller or larger side.
 *
 * @param parts Sides of the cut.
 * @param smaller True to select the lesser area.
 * @returns Index.
 */
function modifierBevelAreaPart(parts: readonly Vector3[][], smaller: boolean): number {
  let best = 0;
  let area = smaller ? Number.POSITIVE_INFINITY : -1;
  for (let index = 0; index < parts.length; index += 1) {
    const next = modifierBevelLoopArea(parts[index] ?? []);
    if (smaller ? next >= area : next <= area) continue;
    area = next;
    best = index;
  }
  return best;
}

/**
 * Returns how far a loop extends from a plane.
 *
 * @param loop Piece vertices.
 * @param plane Center plane.
 * @returns Largest absolute distance. Zero when the loop is missing.
 */
function modifierBevelPenetration(loop: readonly Vector3[] | undefined, plane: SolidPlane): number {
  if (!loop) return 0;
  let depth = 0;
  for (const point of loop) depth = Math.max(depth, Math.abs(plane.signedDistance(point)));
  return depth;
}

/**
 * Packs pieces into a bisect plan.
 *
 * @param face Strip face.
 * @param pieces Cut pieces.
 * @returns Plan.
 */
function modifierBevelLipBisectPlan(face: number, pieces: readonly ModifierBevelLipPiece[]): ModifierBevelBisectPlan {
  return {
    faceIndex: face,
    loops: pieces.map((piece) => piece.loop),
    parents: pieces.map((piece) => piece.parent),
  };
}

/**
 * Returns whether a face has an edge on a center plane.
 *
 * @param shell Derived brush.
 * @param face Face index.
 * @returns True when a neighbor edge lies on a center plane.
 */
function modifierBevelHasPlaneEdge(shell: ModifierBevelDerivedBrush, face: number): boolean {
  return modifierBevelNeighborFaces(shell.localBrush, face).some(
    (neighbor) => modifierBevelEdgeGap(shell, face, neighbor) <= 1e-3,
  );
}

/**
 * Returns whether a face meets another wall off every center plane.
 *
 * @param shell Derived brush.
 * @param records Face records.
 * @param face Face index.
 * @returns True when an off-plane neighbor uses another wall.
 */
function modifierBevelHasForeignEdge(
  shell: ModifierBevelDerivedBrush,
  records: readonly ModifierBevelFaceRecord[],
  face: number,
): boolean {
  const parent = records[face]?.parentSurfaceIndex ?? -1;
  return modifierBevelNeighborFaces(shell.localBrush, face).some((neighbor) =>
    modifierBevelForeignOffPlane(shell, records, face, parent, neighbor),
  );
}

/**
 * Returns whether a neighbor is another wall and misses the center planes.
 *
 * @param shell Derived brush.
 * @param records Face records.
 * @param face Face index.
 * @param parent Current parent.
 * @param neighbor Neighbor face.
 * @returns True when the edge is an off-plane owner seam.
 */
function modifierBevelForeignOffPlane(
  shell: ModifierBevelDerivedBrush,
  records: readonly ModifierBevelFaceRecord[],
  face: number,
  parent: number,
  neighbor: number,
): boolean {
  const record = records[neighbor];
  if (!record || record.parentSurfaceIndex === parent || !modifierBevelGeneratedFace(records, neighbor)) return false;
  return modifierBevelEdgeGap(shell, face, neighbor) > 1e-3;
}

/**
 * Returns the center plane under a face's on-plane edge.
 *
 * @param shell Derived brush.
 * @param face Face index.
 * @returns Plane, or null when no edge lies on one.
 */
function modifierBevelBandPlane(shell: ModifierBevelDerivedBrush, face: number): SolidPlane | null {
  for (const neighbor of modifierBevelNeighborFaces(shell.localBrush, face)) {
    const plane = modifierBevelEdgePlane(shell, face, neighbor);
    if (plane) return plane;
  }
  return null;
}

/**
 * Returns the center plane a shared edge lies on.
 *
 * @param shell Derived brush.
 * @param face First face.
 * @param neighbor Second face.
 * @returns Plane, or null when the edge misses every center.
 */
function modifierBevelEdgePlane(shell: ModifierBevelDerivedBrush, face: number, neighbor: number): SolidPlane | null {
  const edge = modifierBevelSharedEdge(shell.localBrush, face, neighbor);
  if (!edge) return null;
  for (const girder of shell.girders) {
    const plane = modifierBevelCenterPlane(girder);
    if (!plane) continue;
    const gap = Math.max(Math.abs(plane.signedDistance(edge.pointA)), Math.abs(plane.signedDistance(edge.pointB)));
    if (gap <= 1e-3) return plane;
  }
  return null;
}

/**
 * Lists same-wall faces that stay within the lip of one center plane.
 *
 * @param shell Derived brush.
 * @param records Face records.
 * @param start Face on the cut.
 * @param plane Center plane.
 * @returns Band.
 */
function modifierBevelCutBand(
  shell: ModifierBevelDerivedBrush,
  records: readonly ModifierBevelFaceRecord[],
  start: number,
  plane: SolidPlane | null,
): number[] {
  const parent = records[start]?.parentSurfaceIndex ?? -1;
  const band: number[] = [];
  const pending = [start];
  const queued = new Set<number>([start]);
  while (pending.length > 0) modifierBevelTakeBandFace(shell, records, plane, parent, band, pending, queued);
  return band;
}

/**
 * Claims one queued face and queues same-wall neighbors in the lip.
 *
 * @param shell Derived brush.
 * @param records Face records.
 * @param plane Center plane.
 * @param parent Band parent.
 * @param band Band accumulator.
 * @param pending Faces still to visit.
 * @param queued Faces already queued.
 */
function modifierBevelTakeBandFace(
  shell: ModifierBevelDerivedBrush,
  records: readonly ModifierBevelFaceRecord[],
  plane: SolidPlane | null,
  parent: number,
  band: number[],
  pending: number[],
  queued: Set<number>,
): void {
  const face = pending.shift();
  if (face === undefined || !modifierBevelFaceInLip(shell, face, plane)) return;
  band.push(face);
  modifierBevelQueueBandFaces(shell, records, plane, parent, face, pending, queued);
}

/**
 * Queues same-wall neighbors that are not already on the center plane.
 *
 * @param shell Derived brush.
 * @param records Face records.
 * @param plane Center plane.
 * @param parent Band parent.
 * @param face Current face.
 * @param pending Faces still to visit.
 * @param queued Faces already queued.
 */
function modifierBevelQueueBandFaces(
  shell: ModifierBevelDerivedBrush,
  records: readonly ModifierBevelFaceRecord[],
  plane: SolidPlane | null,
  parent: number,
  face: number,
  pending: number[],
  queued: Set<number>,
): void {
  for (const neighbor of modifierBevelNeighborFaces(shell.localBrush, face)) {
    if (queued.has(neighbor) || !modifierBevelBandNeighbor(shell, records, plane, parent, face, neighbor)) continue;
    queued.add(neighbor);
    pending.push(neighbor);
  }
}

/**
 * Returns whether a neighbor continues the band.
 *
 * @param shell Derived brush.
 * @param records Face records.
 * @param plane Center plane.
 * @param parent Band parent.
 * @param face Current face.
 * @param neighbor Neighbor face.
 * @returns True when the neighbor stays in the lip.
 */
function modifierBevelBandNeighbor(
  shell: ModifierBevelDerivedBrush,
  records: readonly ModifierBevelFaceRecord[],
  plane: SolidPlane | null,
  parent: number,
  face: number,
  neighbor: number,
): boolean {
  if (records[neighbor]?.parentSurfaceIndex !== parent || !modifierBevelGeneratedFace(records, neighbor)) return false;
  if (!modifierBevelFaceInLip(shell, neighbor, plane)) return false;
  return modifierBevelEdgeGap(shell, face, neighbor) > 1e-3;
}

/**
 * Returns whether every vertex of a face stays near a plane.
 *
 * @param shell Derived brush.
 * @param face Face index.
 * @param plane Center plane.
 * @returns True when the face is inside the lip.
 */
function modifierBevelFaceInLip(shell: ModifierBevelDerivedBrush, face: number, plane: SolidPlane | null): boolean {
  if (!plane) return false;
  const polygon = shell.localBrush.faces[face];
  const loop = polygon ? shell.localBrush.getFaceVertices(polygon) : [];
  return loop.every((point) => Math.abs(plane.signedDistance(point)) <= 0.04);
}

/**
 * Returns the wall beyond a band when that wall is the only one.
 *
 * @param shell Derived brush.
 * @param records Face records.
 * @param band Faces in the band.
 * @returns Parent, or -1 when the far side is mixed or missing.
 */
function modifierBevelBandParent(
  shell: ModifierBevelDerivedBrush,
  records: readonly ModifierBevelFaceRecord[],
  band: readonly number[],
): number {
  const found: number[] = [];
  const members = new Set(band);
  for (const face of band) modifierBevelCollectBandParents(found, shell, records, members, face);
  return found.length === 1 ? (found[0] ?? -1) : -1;
}

/**
 * Stores walls that meet one band face off the center planes.
 *
 * @param found Parents already stored.
 * @param shell Derived brush.
 * @param records Face records.
 * @param members Faces in the band.
 * @param face Band face.
 */
function modifierBevelCollectBandParents(
  found: number[],
  shell: ModifierBevelDerivedBrush,
  records: readonly ModifierBevelFaceRecord[],
  members: ReadonlySet<number>,
  face: number,
): void {
  const parent = records[face]?.parentSurfaceIndex ?? -1;
  for (const neighbor of modifierBevelNeighborFaces(shell.localBrush, face)) {
    if (members.has(neighbor) || !modifierBevelForeignOffPlane(shell, records, face, parent, neighbor)) continue;
    if (found.includes(records[neighbor]?.parentSurfaceIndex ?? -1)) continue;
    const next = records[neighbor]?.parentSurfaceIndex ?? -1;
    if (next >= 0) found.push(next);
  }
}

/**
 * Returns whether every face just outside the band meets it on a center plane.
 *
 * @param shell Derived brush.
 * @param records Face records.
 * @param band Faces in the band.
 * @returns True when changing the band cannot open a new off-plane seam.
 */
function modifierBevelBandStaysCut(
  shell: ModifierBevelDerivedBrush,
  records: readonly ModifierBevelFaceRecord[],
  band: readonly number[],
): boolean {
  const members = new Set(band);
  return band.every((face) => modifierBevelFaceStaysCut(shell, records, members, face));
}

/**
 * Returns whether one band face meets its old wall only on a center plane.
 *
 * @param shell Derived brush.
 * @param records Face records.
 * @param members Faces in the band.
 * @param face Band face.
 * @returns True when same-wall neighbors outside the band lie on a center
 *   plane.
 */
function modifierBevelFaceStaysCut(
  shell: ModifierBevelDerivedBrush,
  records: readonly ModifierBevelFaceRecord[],
  members: ReadonlySet<number>,
  face: number,
): boolean {
  const parent = records[face]?.parentSurfaceIndex ?? -1;
  return modifierBevelNeighborFaces(shell.localBrush, face).every((neighbor) =>
    modifierBevelNeighborStaysCut(shell, records, members, parent, face, neighbor),
  );
}

/**
 * Returns whether one neighbor is inside the band, another wall, or on a cut.
 *
 * @param shell Derived brush.
 * @param records Face records.
 * @param members Faces in the band.
 * @param parent Band parent.
 * @param face Band face.
 * @param neighbor Neighbor face.
 * @returns True when the neighbor does not keep the old wall off the plane.
 */
function modifierBevelNeighborStaysCut(
  shell: ModifierBevelDerivedBrush,
  records: readonly ModifierBevelFaceRecord[],
  members: ReadonlySet<number>,
  parent: number,
  face: number,
  neighbor: number,
): boolean {
  if (members.has(neighbor) || !modifierBevelGeneratedFace(records, neighbor)) return true;
  if ((records[neighbor]?.parentSurfaceIndex ?? -1) !== parent) return true;
  return modifierBevelEdgeGap(shell, face, neighbor) <= 1e-3;
}

/**
 * Stores one wall on every face of a band.
 *
 * @param records Face records.
 * @param band Faces in the band.
 * @param parent Wall beyond the band.
 */
function modifierBevelPaintBand(records: ModifierBevelFaceRecord[], band: readonly number[], parent: number): void {
  for (const face of band) modifierBevelPaintBandFace(records, face, parent);
}

/**
 * Stores one wall on a band face.
 *
 * @param records Face records.
 * @param face Face index.
 * @param parent Wall beyond the band.
 */
function modifierBevelPaintBandFace(records: ModifierBevelFaceRecord[], face: number, parent: number): void {
  const record = records[face];
  if (!record || record.parentSurfaceIndex === parent) return;
  records[face] = { ...record, parentSurfaceIndex: parent };
}

/**
 * Returns how far a shared edge sits from the nearest center plane.
 *
 * @param shell Derived brush.
 * @param face First face.
 * @param neighbor Second face.
 * @returns Distance, or 1 when the faces do not meet.
 */
function modifierBevelEdgeGap(shell: ModifierBevelDerivedBrush, face: number, neighbor: number): number {
  const edge = modifierBevelSharedEdge(shell.localBrush, face, neighbor);
  if (!edge) return 1;
  let best = Number.POSITIVE_INFINITY;
  for (const girder of shell.girders) best = Math.min(best, modifierBevelGirderGap(girder, edge.pointA, edge.pointB));
  return best;
}

/**
 * Returns how far an edge sits from one center plane.
 *
 * @param girder Authored edge.
 * @param start First endpoint.
 * @param end Second endpoint.
 * @returns Distance, or a huge value when the edge has no center plane.
 */
function modifierBevelGirderGap(girder: ModifierBevelGirder | undefined, start: Vector3, end: Vector3): number {
  const plane = modifierBevelCenterPlane(girder);
  if (!plane) return Number.POSITIVE_INFINITY;
  return Math.max(Math.abs(plane.signedDistance(start)), Math.abs(plane.signedDistance(end)));
}

/**
 * Folds a lip from its new wall when no neighbor of that wall is available.
 *
 * @param records Face records.
 */
function modifierBevelAnchorLipSmears(records: ModifierBevelFaceRecord[]): void {
  for (let face = 0; face < records.length; face += 1) modifierBevelAnchorLipSmear(records, face);
}

/**
 * Points one mismatched generated face at the authored face of its wall.
 *
 * @param records Face records.
 * @param face Face index.
 */
function modifierBevelAnchorLipSmear(records: ModifierBevelFaceRecord[], face: number): void {
  const record = records[face];
  if (!record || !modifierBevelGeneratedFace(records, face) || modifierBevelLipSmearMatches(records, record)) return;
  const source = modifierBevelAuthoredParentFace(records, record.parentSurfaceIndex);
  if (source < 0) return;
  records[face] = { ...record, smearFromDerivedIndex: source };
}

/**
 * Returns whether a record already folds from its own wall.
 *
 * @param records Face records.
 * @param record Face record.
 * @returns True when the source matches, or there is no source.
 */
function modifierBevelLipSmearMatches(
  records: readonly ModifierBevelFaceRecord[],
  record: ModifierBevelFaceRecord,
): boolean {
  if (record.smearFromDerivedIndex < 0) return true;
  const source = records[record.smearFromDerivedIndex];
  return !source || source.parentSurfaceIndex === record.parentSurfaceIndex;
}

/**
 * Returns the authored face of one wall.
 *
 * @param records Face records.
 * @param parent Authored parent.
 * @returns Face index, or -1.
 */
function modifierBevelAuthoredParentFace(records: readonly ModifierBevelFaceRecord[], parent: number): number {
  for (let face = 0; face < records.length; face += 1) {
    const record = records[face];
    if (!record || record.parentSurfaceIndex !== parent || record.chamferEdge || record.cornerFace) continue;
    return face;
  }
  return -1;
}
